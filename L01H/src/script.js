// Exercício 7H - Calcular volume de uma caixa retangular

alert("Volume da caixa retangular");

let comprimento = parseFloat(prompt("Informe o comprimento: "));

let largura = parseFloat(prompt("Informe a largura: "));

let altura = parseFloat(prompt("Informe a altura: "));

let volume = comprimento * largura * altura;

alert("O volume da caixa é: " + volume);